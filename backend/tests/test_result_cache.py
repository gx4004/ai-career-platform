def test_cache_key_changes_with_user_scope():
    base = compute_content_hash("resume", "alice resume", "junior backend role")
    user_a = compute_content_hash(
        "resume", "alice resume", "junior backend role", user_scope="user-a"
    )
    user_b = compute_content_hash(
        "resume", "alice resume", "junior backend role", user_scope="user-b"
    )
    guest = compute_content_hash(
        "resume", "alice resume", "junior backend role", user_scope="guest"
    )

    assert base != user_a
    assert user_a != user_b
    assert user_a != guest
    assert guest != user_b


def test_cache_key_stable_for_same_user_and_inputs():
    """Same scope + same inputs → same hash (idempotent)."""
    a = compute_content_hash("resume", "  Alice Resume  ", "Backend role", user_scope="user-x")
    b = compute_content_hash("resume", "alice resume", "backend role", user_scope="user-x")
    # The function lowercases + strips inputs, so these collapse.
    assert a == b


def test_cache_key_changes_with_inputs_for_same_user():
    """Within one user, different inputs → different hashes."""
    a = compute_content_hash("resume", "alice resume v1", "role", user_scope="user-x")
    b = compute_content_hash("resume", "alice resume v2", "role", user_scope="user-x")
    assert a != b


def test_cache_key_changes_with_prompt_version():
    """A prompt template change must invalidate cached responses immediately,
    not wait for the TTL window. Routers pass prompt_version through
    cache_extra_keys; this test locks that contract at the hash boundary."""
    base = compute_content_hash(
        "resume",
        "alice resume",
        "junior backend role",
        user_scope="user-x",
        prompt_version="2026-04-28-v1",
    )
    bumped = compute_content_hash(
        "resume",
        "alice resume",
        "junior backend role",
        user_scope="user-x",
        prompt_version="2026-04-28-v2",
    )
    assert base != bumped


def test_cache_key_changes_with_model():
    """Switching LLM models (Gemini Flash → Pro, or Flash → next-gen) must
    not return responses generated by the old model."""
    base = compute_content_hash(
        "resume",
        "alice resume",
        "junior backend role",
        user_scope="user-x",
        model="gemini-2.5-flash",
    )
    bumped = compute_content_hash(
        "resume",
        "alice resume",
        "junior backend role",
        user_scope="user-x",
        model="gemini-2.6-pro",
    )
    assert base != bumped


def test_cache_key_changes_with_llm_provider():
    """`tool_pipeline.run_tool_pipeline` keys every cache lookup on
    `settings.LLM_PROVIDER` (unconditionally, not just via a router's
    `cache_extra_keys`). Two providers can otherwise share a model string
    (google/vertex both default to "gemini-2.5-flash") or the caller may not
    know its own effective model at all (anthropic's own default lives inside
    `ai_client.complete_structured`, not in `settings.LLM_MODEL`) — either way
    an operator switching providers must never see the other provider's
    cached output."""
    vertex = compute_content_hash(
        "resume",
        "alice resume",
        "junior backend role",
        user_scope="user-x",
        model="gemini-2.5-flash",
        llm_provider="vertex",
    )
    anthropic = compute_content_hash(
        "resume",
        "alice resume",
        "junior backend role",
        user_scope="user-x",
        model="gemini-2.5-flash",
        llm_provider="anthropic",
    )
    assert vertex != anthropic


